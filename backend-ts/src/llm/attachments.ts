/** A legacy file piece (`utf8-v1` text, `native-v1` PDF / video). */
export const isFilePiece = (v: unknown): v is FilePiece => FilePieceSchema.safeParse(v).success
/** A PDF / video reference piece (`ref-v1`). */
export const isRefPiece = (v: unknown): v is RefFilePiece =>
  typeof v === 'object' && v !== null && (v as { representation?: unknown }).representation === REF_REPRESENTATION && RefFilePieceSchema.safeParse(v).success
/** Either kind of file piece. */
export const isAnyFilePiece = (v: unknown): v is FilePiece | RefFilePiece => isFilePiece(v) || isRefPiece(v)
export function attachmentPiece(a: Attachment): AttachmentPiece { return 'file_kind' in a ? { kind: 'file', ...a } : imagePiece(a) }
/** The bytes of an image or a legacy file attachment (a reference's go through RefAccess). `check`, when the reader
 *  has it, says from the database alone (nothing read) whether the attachment is still the session's as recorded —
 *  what a cache in front of the reader asks again on every hit. */
export type AttachmentReader = ((attachment: Attachment) => Uint8Array | null) & { check?: (attachment: Attachment) => boolean }
export function assetAttachment(asset: Asset): Attachment {
  const ref = refFromAsset(asset)
  if (ref) return ref
  const m = asset.meta
  return AttachmentSchema.parse({ ...m, asset_id: asset.id, sha256: asset.sha256, bytes: asset.byte_size })
}
const isRefAttachment = (a: unknown): boolean => typeof a === 'object' && a !== null && (a as { representation?: unknown }).representation === REF_REPRESENTATION

/** The lookup may not widen the owning session. Reference metadata is immutable too, not only the hash. A reference
 *  (`ref-v1`) is never read through here: null. */
export function attachmentReader(lookup: (id: string) => Asset | null, read: (path: string) => Uint8Array, project: string, session: string): AttachmentReader {
  // the asset row of a legacy attachment, every recorded field equal to the piece's, at a path the store wrote — or null
  const recordOf = (ref: Attachment): Asset | null => {
    try {
      if (isRefAttachment(ref)) return null
      const a = lookup(ref.asset_id)
      if (!a || a.project_id !== project || a.meta.session_id !== session || a.meta.role !== 'attachment') return null
      const actual = assetAttachment(a)
      if (isRefAttachment(actual) || !('sha256' in ref)) return null
      const kind = 'file_kind' in actual ? actual.file_kind === 'text' ? 'text' : 'data' : 'image'
      if (a.kind !== kind || Object.entries(actual).some(([key, value]) => (ref as unknown as Record<string, unknown>)[key] !== value)) return null
      // Stored paths are generated by AssetStore, never client paths (also rejects a tampered DB path).
      const storagePath = a.storage_path.replace(/\\/g, '/')
      if (!/^[^./\\]+\/(image|text|data)\/[a-f0-9]{16}\.[a-z0-9]+$/.test(storagePath) || !storagePath.startsWith(`${project}/${kind}/`)) return null
      return a
    } catch { return null }
  }
  const reader: AttachmentReader = (ref) => {
    try {
      const a = recordOf(ref)
      if (a === null) return null
      const bytes = read(a.storage_path)
      if (bytes.length !== ref.bytes || sha256Hex(bytes) !== (ref as { sha256: string }).sha256) return null
      // Validate legacy file metadata against bytes on every read. Legacy images retain their original filename semantics.
      const measured = measureAttachment(bytes, 'file_kind' in ref ? ref.file_kind === 'text' ? 'attachment.txt' : ref.name : '', ref.media_type)
      if (Object.entries(measured).some(([key, value]) => (ref as unknown as Record<string, unknown>)[key] !== value)) return null
      return bytes
    } catch { return null }
  }
  reader.check = (ref) => recordOf(ref) !== null
  return reader
}

/** Every field of an attachment piece, in a fixed order: what a cached read is keyed by (the same asset and hash under
 *  another name, type, size or kind is another key, and is read and checked again). */
function frozenKey(attachment: Attachment): string {
  const o = attachment as unknown as Record<string, unknown>
  return JSON.stringify(Object.keys(o).filter((k) => k !== 'data').sort().map((k) => [k, o[k]]))
}

/** A reader that keeps what it read, keyed by every frozen field of the piece, up to `capBytes`: a run's requests
 *  carry the same history again and again, so its images and legacy files are read and hashed once. A hit is still
 *  checked against the database every time (`read.check`: this session's, every recorded field equal) — a row that
 *  changed since is not answered from the cache. */
export function memoizedReader(read: AttachmentReader, capBytes: number = PROVIDER_REQUEST_LIMITS.app_cap.request_bytes): AttachmentReader {
  const kept = new Map<string, Uint8Array>()
  let held = 0
  const memo: AttachmentReader = (attachment) => {
    const key = frozenKey(attachment)
    const hit = kept.get(key)
    if (hit) {
      if (read.check && !read.check(attachment)) { kept.delete(key); held -= hit.length; return null }
      return hit
    }
    const bytes = read(attachment)
    if (bytes && bytes.length <= capBytes) {
      while (held + bytes.length > capBytes && kept.size) {
        const [first, value] = kept.entries().next().value as [string, Uint8Array]
        kept.delete(first)
        held -= value.length
      }
      kept.set(key, bytes)
      held += bytes.length
    }
    return bytes
  }
  if (read.check) memo.check = read.check
  return memo
}
export function textEnvelope(file: FilePiece, content: string): string {
  return `[attached UTF-8 file v1: ${JSON.stringify(file.name)}; bytes=${file.bytes}; sha256=${file.sha256}]\n${content}\n[end attached file v1]`
}

/** Where a legacy (`native-v1`) file the route does not take itself is kept for the run's tools: its absolute path, the
 *  file put there once (the same file, the same path — every request says the same words). `load` gives the file's
 *  bytes, checked against its record; a placer calls it only when it places the file (never again once it has placed
 *  or refused it), so a repeated request reads and hashes nothing. The one placer of the app is
 *  workspace/legacy_attachment_placer.ts (a confined writer, fail closed); the harness never writes into a folder a
 *  command writes. References (`ref-v1`) are never placed: they are named where they are. */
export type AttachmentPlacer = (file: FilePiece, load: () => Uint8Array) => string

/** The words that stand for a legacy file the route does not take itself: what it is and where the run's tools find it. */
export function placedFileNote(file: FilePiece, path: string): string {
  return `[attached file: ${JSON.stringify(file.name)}; ${file.media_type}; ${file.bytes} bytes; this model does not take it directly; saved at ${path}]`
}

/** The route a request goes to, as its attachments see it. */
export interface AttachmentRoute {
  capabilities: Record<string, unknown>
  /** the bounds of one request on the route (requestLimitsFor); the application cap when not said */
  limits?: RequestLimits
  /** the session's references (absent: a reference in the messages is refused) */
  refs?: RefAccess | null
}

/** Whether a piece's bytes travel on the route: an image the route takes, a legacy file it takes, a reference that
 *  refNativeFor admits. The piece and the route decide — nothing else. */
export function travelsNatively(piece: ImagePiece | FilePiece | RefFilePiece, capabilities: Record<string, unknown>, limits: RequestLimits): boolean {
  if (isImagePiece(piece)) return capabilities.images === true
  if (isRefPiece(piece)) return refNativeFor(capabilities, limits, piece)
  return (piece as FilePiece).representation === 'native-v1' && nativeAttachment(capabilities, piece)
}

/** Every attachment piece of the messages checked without reading a file: its shape, the route's gate (an image or a
 *  text the route does not take), a reference against its asset row, a file in a tool's return refused — then the
 *  bytes all native pieces together would make the request carry, refused when over the route's bounds. Nothing is
 *  read before this has passed. */
export function surveyAttachments(messages: ModelMessage[], label: string, route: AttachmentRoute, { total = true }: { total?: boolean } = {}): { native: (ImagePiece | FilePiece | RefFilePiece)[] } {
  const limits = route.limits ?? PROVIDER_REQUEST_LIMITS.app_cap
  const native: (ImagePiece | FilePiece | RefFilePiece)[] = []
  const visit = (v: unknown, tool: boolean): void => {
    if (!v || typeof v !== 'object' || !['file', 'image'].includes(String((v as { kind?: unknown }).kind))) return
    if (!isAnyFilePiece(v) && !isImagePiece(v)) throw new Error('invalid attachment reference in history')
    if (tool && isAnyFilePiece(v)) throw new Error('native file tool results are not supported; attach PDF/video through the composer')
    const refusal = attachmentRefusal(route.capabilities, [v], label)
    if (refusal) throw new Error(refusal)
    if (isRefPiece(v)) {
      if (!route.refs) throw new Error(`${label}: this request has no access to the session's file references: ${v.name}`)
      const why = route.refs.check(v)
      if (why) throw new Error(`attachment reference invalid or outside this session: ${v.name} (${why})`)
    }
    if (travelsNatively(v, route.capabilities, limits)) native.push(v)
  }
  for (const m of messages) {
    if (!isRequest(m)) continue
    for (const p of m.parts) {
      if (isUserPrompt(p) && Array.isArray(p.content)) for (const v of p.content) visit(v, false)
      else if (isToolReturn(p) && p.content && typeof p.content === 'object' && !Array.isArray(p.content)) for (const v of Object.values(p.content)) visit(v, true)
    }
  }
  if (total) totalCheck(native, limits, label)
  return { native }
}

/** The native pieces' total weighed against the route's bounds: an image by what it is sent as (`sent`: its planned
 *  bytes, by hash), anything else by its record. */
function totalCheck(native: readonly (ImagePiece | FilePiece | RefFilePiece)[], limits: RequestLimits, label: string, sent: ReadonlyMap<string, FittedImage> = new Map()): void {
  const over = nativeTotalRefusal(limits, native.map((v) => ({ bytes: isImagePiece(v) ? (sent.get(v.sha256)?.bytes.length ?? v.bytes) : v.bytes, input_file: !isImagePiece(v) && v.media_type === 'application/pdf' })), label)
  if (over) throw new Error(over)
}

/** The references judged, then — on a route whose images are fitted before they go (image_fit.ts) — the images read
 *  and planned and the total weighed by what they are sent as; on any other route the total is weighed from the
 *  records before anything is read. Returns the plan (empty where nothing is fitted). */
function surveyAndPlan(messages: ModelMessage[], label: string, route: AttachmentRoute, readImage: (piece: ImagePiece) => Uint8Array): { native: (ImagePiece | FilePiece | RefFilePiece)[]; plan: Map<string, FittedImage> } {
  const limits = route.limits ?? PROVIDER_REQUEST_LIMITS.app_cap
  if (IMAGE_SEND_MAX_SIDE[limits.key] === undefined) return { ...surveyAttachments(messages, label, route), plan: new Map() }
  const { native } = surveyAttachments(messages, label, route, { total: false })
  const images = native.filter(isImagePiece) as ImagePiece[]
  const others = native.filter((v) => !isImagePiece(v)).reduce((n, v) => n + 4 * Math.ceil(v.bytes / 3), 0)
  // the words: the messages as they stand, their images still references (no bytes)
  const words = Buffer.byteLength(JSON.stringify(messages))
  const plan = planRequestImages(images.map((i) => ({ sha256: i.sha256, media_type: i.media_type, bytes: readImage(i) })), limits, others + words)
  totalCheck(native, limits, label, plan)
  return { native, plan }
}

export function hydrateAttachments(messages: ModelMessage[], read: AttachmentReader, capabilities: Record<string, unknown>, label: string, place: AttachmentPlacer | null = null,
  route: Omit<AttachmentRoute, 'capabilities'> = {}): ModelMessage[] {
  const limits = route.limits ?? PROVIDER_REQUEST_LIMITS.app_cap
  const loadImage = (image: ImagePiece): Uint8Array => {
    const bytes = read(image)
    if (!bytes || bytes.length !== image.bytes || sha256Hex(bytes) !== image.sha256) throw new Error(`attachment missing, damaged or outside this session: ${image.name}`)
    return bytes
  }
  // everything is judged from the references first: a request that cannot go is refused before any file is read (on a
  // route whose images are fitted, before any but the images, which the plan of what they are sent as needs)
  const { plan } = surveyAndPlan(messages, label, { ...route, capabilities, limits }, loadImage)
  const hydrate = (piece: unknown): unknown => {
    if (!piece || typeof piece !== 'object' || !['file', 'image'].includes(String((piece as { kind?: unknown }).kind))) return piece
    if (isRefPiece(piece)) {
      // a reference: its bytes when the route takes it, else its one fixed line — nothing read, hashed or stat'ed
      if (!refNativeFor(capabilities, limits, piece)) return refFileNote(piece)
      return { ...piece, data: Buffer.from(route.refs!.read(piece)).toString('base64') }
    }
    const legacy = piece as ImagePiece | FilePiece
    const missing = () => new Error(`attachment missing, damaged or outside this session: ${legacy.name}`)
    const load = (): Uint8Array => {
      const bytes = read(legacy)
      if (!bytes || bytes.length !== legacy.bytes || sha256Hex(bytes) !== legacy.sha256) throw missing()
      return bytes
    }
    // a legacy PDF or video this route does not take: saved for the run's tools, the request names where — the record
    // checked (the database only); its bytes read only if the placer places it now, never on a later request
    if (isFilePiece(legacy) && legacy.representation === 'native-v1' && !nativeAttachment(capabilities, legacy)) {
      if (!place) throw new Error(`${label} does not take ${legacy.media_type} directly and this run has no folder to keep it in: ${legacy.name}`)
      if (read.check && !read.check(legacy)) throw missing()
      return placedFileNote(legacy, place(legacy, load))
    }
    const bytes = load()
    if (isFilePiece(legacy) && legacy.representation === 'utf8-v1') return { ...legacy, data: textEnvelope(legacy, decodeText(bytes)) }
    // an image goes as the plan has it (image_fit.ts: fitted to the provider's side, a JPEG when the request would not
    // fit otherwise); the record keeps the original
    const sent = isImagePiece(legacy) ? plan.get(legacy.sha256) : undefined
    if (sent) return { ...legacy, media_type: sent.media_type, data: Buffer.from(sent.bytes).toString('base64') }
    return { ...legacy, data: Buffer.from(bytes).toString('base64') }
  }
  return messages.map((m) => !isRequest(m) ? m : { ...m, parts: m.parts.map((p) => {
    if (isUserPrompt(p) && Array.isArray(p.content)) return { ...p, content: p.content.map((v) => hydrate(v)) } as typeof p
    if (isToolReturn(p) && p.content && typeof p.content === 'object' && !Array.isArray(p.content)) return { ...p, content: Object.fromEntries(Object.entries(p.content).map(([k, v]) => [k, hydrate(v)])) }
    return p
  }) })
}
export class AttachmentHydration extends WrapperModel {
  private readonly read: AttachmentReader
  constructor(wrapped: Model, read: AttachmentReader, private readonly capabilities: Record<string, unknown>, private readonly place: AttachmentPlacer | null = null,
    private readonly attachmentRoute: Omit<AttachmentRoute, 'capabilities'> = {}) {
    super(wrapped)
    // a run's requests repeat its history: what was read once (and checked against its hash) is kept for the next
    this.read = memoizedReader(read, (attachmentRoute.limits ?? PROVIDER_REQUEST_LIMITS.app_cap).request_bytes)
  }
  override request(messages: ModelMessage[], settings: ModelSettings, params: ModelRequestParameters, ctx?: RequestContext) {
    return this.wrapped.request(hydrateAttachments(messages, this.read, this.capabilities, this.model_name, this.place, this.attachmentRoute), settings, params, ctx)
  }
  override requestStream(messages: ModelMessage[], settings: ModelSettings, params: ModelRequestParameters, ctx?: RequestContext) {
    return this.wrapped.requestStream(hydrateAttachments(messages, this.read, this.capabilities, this.model_name, this.place, this.attachmentRoute), settings, params, ctx)
  }
}

/** Preflight before accepting a new run, so an incompatible replay cannot consume the person's draft: first every
 *  piece judged from its reference alone (the route's gate, the session's records, the bounds of one request), then
 *  the images and legacy files read as before, and each reference the route takes natively opened and compared with
 *  what was attached (nothing of it read). A reference named by its path is not touched at all: a file moved away
 *  since does not lock the conversation. */
export function checkAttachmentHistory(messages: ModelMessage[], read: AttachmentReader, capabilities: Record<string, unknown>, label: string,
  route: Omit<AttachmentRoute, 'capabilities'> = {}): void {
  // the total weighed as the request would send it: on a route whose images are fitted, by what they go as
  const { native } = surveyAndPlan(messages, label, { ...route, capabilities }, (image) => {
    const bytes = read(image)
    if (!bytes) throw new Error(`attachment missing, damaged or outside this session: ${image.name}`)
    return bytes
  })
  for (const m of messages) {
    if (!isRequest(m)) continue
    for (const p of m.parts) {
      const values = isUserPrompt(p) && Array.isArray(p.content) ? p.content : isToolReturn(p) && p.content && typeof p.content === 'object' ? Object.values(p.content) : []
      for (const v of values) {
        if (!isFilePiece(v) && !isImagePiece(v)) continue
        // a legacy PDF or video this route names by its placed path: its record only (the placer reads it, once)
        const placedOnly = isFilePiece(v) && v.representation === 'native-v1' && !nativeAttachment(capabilities, v)
        if (placedOnly && read.check) { if (!read.check(v)) throw new Error(`attachment missing, damaged or outside this session: ${v.name}`); continue }
        if (!read(v)) throw new Error(`attachment missing, damaged or outside this session: ${v.name}`)
      }
    }
  }
  for (const piece of native) {
    if (!isRefPiece(piece)) continue
    const why = route.refs!.verify(piece)
    if (why) throw new Error(why)
  }
}
